/*
 * hdf5lib: src/all_hdf5.c
 *
 * Purpose:
 * This file's sole purpose is to create explicit references to HDF5 API
 * functions. This forces the linker to include the corresponding object
 * code from the static libhdf5.a into the final hdf5lib shared library
 * (hdf5lib.so or hdf5lib.dll).
 *
 * By including the full HDF5 codebase, `R CMD check` can perform a more
 * thorough scan for potentially disallowed C function calls (e.g., printf,
 * abort, exit) within the HDF5 library itself, allowing them to be
 * addressed here rather than causing issues in downstream packages.
 *
 * Generation:
 * The function list below should be generated, typically by using `nm`
 * on the final libhdf5.a produced by the configure script and extracting
 * all defined function symbols (marked with ' T ').
 * Example: nm path/to/libhdf5.a | grep ' T ' | awk '{print $3}'
 */

